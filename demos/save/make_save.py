"""Generates the font of the save demo's on-screen log.

Usage: make_save.py <assets dir> <output resource dir>
<assets dir> must contain PT_Serif-Web-Regular.ttf (see ../dialog/fetch_assets.sh).
Writes textures/fonts/demo_log.tga.tx and ini/fonts.ini. The sea, the sky and the ship come from
../sea/make_sea.py and ../ship/make_ship.py.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "common"))
from storm_formats import write_fonts  # noqa: E402

# name: (TrueType file, pixel size, outline); the log prints it at scale 1 over the 800x600 screen
FONTS = {
    "demo_log": ("PT_Serif-Web-Regular.ttf", 20, 1),
}


def main():
    assets, resource = Path(sys.argv[1]), Path(sys.argv[2])
    write_fonts({name: (assets / ttf, size, outline) for name, (ttf, size, outline) in FONTS.items()}, resource,
                "generated by make_save.py from PT Serif (SIL Open Font License)")


if __name__ == "__main__":
    main()
